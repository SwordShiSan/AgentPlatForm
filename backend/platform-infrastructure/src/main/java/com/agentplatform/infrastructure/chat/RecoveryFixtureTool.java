package com.agentplatform.infrastructure.chat;

import com.agentplatform.domain.harness.HarnessPorts.ToolExecutionPort;
import com.agentplatform.types.harness.HarnessData.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;
import java.util.concurrent.*;

/** Fixed deterministic acceptance capability. Never registered by the production composition. */
public final class RecoveryFixtureTool implements ToolExecutionPort {
    public static final List<Call> DEFINITIONS=List.of(new Call("fixture-definition","recovery_probe",Map.of("text",""),false),
            new Call("approval-definition","approval_probe",Map.of("text",""),false));
    private final Path root;
    public RecoveryFixtureTool(Path root) {this.root=root.toAbsolutePath().normalize();}
    @Override public CompletionStage<Observation> execute(Scope scope,Call call) {
        try {
            if(!Set.of("recovery_probe","approval_probe").contains(call.name())||!call.arguments().keySet().equals(Set.of("text"))||!(call.arguments().get("text") instanceof String text)||text.length()>256)
                throw new IllegalArgumentException("FIXTURE_TOOL_ARGUMENTS_INVALID");
            // Scope IDs are generated by the platform, never accepted as filesystem paths.
            UUID task=UUID.fromString(scope.taskId());
            String name=HexFormat.of().formatHex(java.security.MessageDigest.getInstance("SHA-256").digest(call.id().getBytes(StandardCharsets.UTF_8)));
            Path directory=root.resolve(task.toString());Files.createDirectories(directory);
            Files.writeString(directory.resolve(name+".effect"),"effect",StandardOpenOption.CREATE_NEW);
            return CompletableFuture.completedFuture(new Observation(call.id(),call.name(),"fixture:"+text,OperationStatus.SUCCEEDED));
        } catch(Exception error) {return CompletableFuture.failedFuture(error);}
    }
}
